import * as React from 'react';
import { act } from 'react-dom/test-utils';
import { createRoot, type Root } from 'react-dom/client';
import { beforeEach, afterEach, it, expect, vi } from 'vitest';
import { CanvasVideoSeparateButton } from '@/components/canvas/CanvasVideoSeparateButton';
import { CanvasReadOnlyContext } from '@/components/canvas/CanvasReadOnlyContext';
import type { CanvasVideoSeparationJob } from '@/lib/canvas/video-separation';
let root: Root, host: HTMLDivElement;
beforeEach(() => { vi.stubGlobal('IS_REACT_ACT_ENVIRONMENT', true); host = document.createElement('div'); document.body.append(host); root = createRoot(host); });
afterEach(() => { act(() => root.unmount()); host.remove(); vi.unstubAllGlobals(); });
const mount = (run: any, readOnly = false, job?: CanvasVideoSeparationJob) => act(() => root.render(React.createElement(CanvasReadOnlyContext.Provider, { value: readOnly }, React.createElement(CanvasVideoSeparateButton, { onSeparate: run, job }))));
const open = () => act(() => host.querySelector<HTMLButtonElement>('[aria-label="音视频分离"]')!.click());
it.each(['tracks', 'vocals', 'background'] as const)('starts %s and survives closing and reopening the toolbar', async mode => {
  let finish: () => void = () => {};
  let completed = false;
  const run = vi.fn(() => new Promise<void>(resolve => { finish = resolve; }).then(() => { completed = true; }));
  mount(run); open();
  expect([...host.querySelectorAll('button')].slice(1).map(button => button.textContent)).toEqual(['音视频分离', '人声提取', '背景音提取']);
  await act(async () => host.querySelectorAll('button')[['tracks', 'vocals', 'background'].indexOf(mode) + 1].click());
  expect(run).toHaveBeenCalledWith(mode);
  const job = { mode, status: 'running' as const, progress: .5 };
  mount(run, false, job);
  expect(host.textContent).toContain(mode === 'tracks' ? '50%' : '提取中');
  act(() => root.render(null));
  expect(completed).toBe(false);
  mount(run, false, job);
  expect(host.querySelector('button')!.disabled).toBe(true);
  act(() => host.querySelector('button')!.click()); expect(run).toHaveBeenCalledOnce();
  await act(async () => finish()); expect(completed).toBe(true);
  mount(run, false, { ...job, status: 'success', progress: 1 });
  expect(host.querySelector('button')!.disabled).toBe(false);
});
it('shows a retained failure and allows reopening and retrying', async () => {
  const run = vi.fn().mockResolvedValue(undefined);
  mount(run, false, { mode: 'vocals', status: 'error', progress: 0, error: '没有音轨' });
  expect(host.querySelector('[role="alert"]')?.textContent).toContain('没有音轨');
  open(); expect(host.querySelector('[role="alert"]')).toBeNull(); await act(async () => host.querySelectorAll('button')[2].click());
  expect(run).toHaveBeenCalledWith('vocals');
});
it('hides the mutation on read-only canvases', () => { mount(vi.fn(), true); expect(host.querySelector('button')).toBeNull(); });
